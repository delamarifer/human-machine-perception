"""Writes ddpm-grid-data.js: the 12 images of assets/horses as 40 x 40 gray levels, for the scene ddpm-grid.html.
Why a file and not the browser: the browser's first decode of an image can differ by a gray level or two from later
decodes, and a few image runs end near a tie between two training images, so the grid changed from one load to the next.
With fixed pixels the grid is the same on every load. Same recipe as d8LoadImages in d8-toy.js: centered square crop,
resize (area average), gray = .299 R + .587 G + .114 B. Run from this folder: python3 ddpm-grid-data.py"""
import base64
from pathlib import Path
from PIL import Image

N = 40
here = Path(__file__).resolve().parent
names = [f"h{i:02d}.{'png' if i <= 5 else ('jpg' if i == 10 else 'webp')}" for i in range(1, 13)]
rows = []
for name in names:
    im = Image.open(here.parent / 'assets' / 'horses' / name).convert('RGB')
    m = min(im.size)
    left, top = (im.width - m) // 2, (im.height - m) // 2
    im = im.crop((left, top, left + m, top + m)).resize((N, N), Image.Resampling.BOX)
    px = im.tobytes()
    g = bytes(max(0, min(255, round(.299 * px[i] + .587 * px[i + 1] + .114 * px[i + 2]))) for i in range(0, len(px), 3))
    rows.append(base64.b64encode(g).decode())
body = ',\n'.join(f'  "{r}"' for r in rows)
(here / 'ddpm-grid-data.js').write_text(
    "/* Generated by ddpm-grid-data.py: the 12 images of assets/horses, 40 x 40 gray levels (0 to 255), base64, in order h01 to h12. */\n"
    f"const DDPMG_H40 = [\n{body}\n];\n")
print('wrote', len(rows), 'images')
