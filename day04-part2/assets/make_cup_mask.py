#!/usr/bin/env python3
"""Cup mask for the benchmark slides, from day04/assets/photos/coffee.jpg (1280 x 853).

    python3 day04-part2/assets/make_cup_mask.py      (from the repo root; needs opencv-python, numpy)

GrabCut, seeded with the cup's measured extents: body x 442-726, y 268-537; handle x 697-785, y 330-452.
Writes day04-part2/assets/cup-mask.js: the outline and handle hole as polygons, the bounding box and the area.
The mask is our annotation for a teaching example, not a dataset label.
"""
import json
import cv2
import numpy as np

im = cv2.imread('day04/assets/photos/coffee.jpg')
H, W = im.shape[:2]
m = np.full((H, W), cv2.GC_BGD, np.uint8)
m[255:545, 430:795] = cv2.GC_PR_BGD                       # search window around the cup
cv2.ellipse(m, (584, 400), (135, 128), 0, 0, 360, cv2.GC_PR_FGD, -1)   # body
cv2.ellipse(m, (584, 400), (95, 95), 0, 0, 360, cv2.GC_FGD, -1)
cv2.ellipse(m, (740, 392), (42, 60), 0, 0, 360, cv2.GC_PR_FGD, -1)     # handle ring
m[452:, :445] = cv2.GC_BGD                                # saucer, left of the body
m[470:, 700:] = cv2.GC_BGD                                # saucer, right of the body
cv2.fillPoly(m, [np.array([(430, 445), (455, 445), (470, 462), (498, 520), (515, 540), (430, 545)])], cv2.GC_BGD)   # saucer, lower left
cv2.fillPoly(m, [np.array([(786, 392), (800, 380), (800, 470), (700, 470), (738, 447), (768, 425)])], cv2.GC_BGD)   # fingers, right of the handle
bg, fg = np.zeros((1, 65)), np.zeros((1, 65))
cv2.grabCut(im, m, None, bg, fg, 8, cv2.GC_INIT_WITH_MASK)
mask = ((m == cv2.GC_FGD) | (m == cv2.GC_PR_FGD)).astype(np.uint8)
mask = cv2.morphologyEx(mask, cv2.MORPH_OPEN, np.ones((5, 5), np.uint8))
mask = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, np.ones((9, 9), np.uint8))

n, lab, stats, _ = cv2.connectedComponentsWithStats(mask)
big = 1 + int(np.argmax(stats[1:, cv2.CC_STAT_AREA]))
mask = (lab == big).astype(np.uint8)
cs, _ = cv2.findContours(mask, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_SIMPLE)
outer = max(cs, key=cv2.contourArea)
polys = [cv2.approxPolyDP(c, 1.5, True)[:, 0, :].tolist() for c in cs if cv2.contourArea(c) > 100]   # outline, then the hole in the handle
x, y, w, h = cv2.boundingRect(outer)
print('area', int(mask.sum()), 'bbox', [x, y, x + w, y + h], 'rings', len(polys))

json_out = {'size': [W, H], 'box': [x, y, x + w, y + h], 'area': int(mask.sum()), 'polys': polys}
open('day04-part2/assets/cup-mask.js', 'w').write(
    '/* Generated by make_cup_mask.py. Do not edit by hand. */\nconst CUP = ' + json.dumps(json_out) + ';\n')

view = im.copy()
view[mask > 0] = (0.5 * view[mask > 0] + 0.5 * np.array([6, 119, 217])).astype(np.uint8)
cv2.rectangle(view, (x, y), (x + w, y + h), (0, 0, 0), 2)
cv2.imwrite('/private/tmp/claude-501/-Users-shreyalpandit--claude-spares-spare-6hjnpP/3dd313b4-f4fe-4909-b5ca-9d552bc819cd/scratchpad/cup-view.jpg', view[220:580, 340:860])
