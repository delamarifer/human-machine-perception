/* Shared helpers for the linear-filtering parts. Loaded by deck.html before the parts.
   Every image is generated by make_figures.py into assets/. */
const AS = 'assets/';
const stepAttr = s => s != null ? ` data-step="${s}"` : '';
const bcls = s => s != null ? ' b' : '';

/* one figure: im('crop-s2.jpg', 'σ = 2', {step: 1}) */
const im = (f, cap = '', o = {}) => `
  <figure class="lf-fig${bcls(o.step)}"${stepAttr(o.step)}${o.style ? ` style="${o.style}"` : ''}>
    <img src="${AS}${f}" alt="${String(cap).replace(/<[^>]+>/g, '')}"${o.px ? ' class="px"' : ''}>
    ${cap ? `<figcaption>${cap}</figcaption>` : ''}
  </figure>`;

/* a grid of figures, n columns; rows share the remaining height */
const grid = (n, items, o = {}) => {
  const rows = Math.ceil(items.length / n);
  return `<div class="lf-grid${bcls(o.step)}"${stepAttr(o.step)} style="grid-template-columns:repeat(${n},minmax(0,1fr));` +
    `grid-template-rows:repeat(${rows},minmax(0,1fr));${o.style || ''}">${items.join('')}</div>`;
};

/* a text panel with a bold lead line */
const card = (head, body, step, o = {}) => `
  <div class="lf-card${bcls(step)}${o.cls ? ' ' + o.cls : ''}"${stepAttr(step)}${o.style ? ` style="${o.style}"` : ''}>
    ${head ? `<div class="lf-head">${head}</div>` : ''}${body ? `<div class="label">${body}</div>` : ''}
  </div>`;

/* an equation box */
const eq = (html, step, o = {}) => `<div class="lf-eq${bcls(step)}"${stepAttr(step)}${o.style ? ` style="${o.style}"` : ''}>${html}</div>`;

/* a kernel as a grid of numbers: positive blue, negative red, zero white */
const ker = (mat, o = {}) => {
  const cols = mat[0].length;
  const cells = mat.flat().map(v => {
    const t = String(v).replace('-', '−');
    const n = typeof v === 'number' ? v : (t.startsWith('−') ? -1 : (parseFloat(t) === 0 ? 0 : 1));
    return `<span class="${n > 0 ? 'pos' : n < 0 ? 'neg' : ''}">${t}</span>`;
  }).join('');
  return `<div class="lf-kwrap${bcls(o.step)}"${stepAttr(o.step)}>
    ${o.scale ? `<span class="lf-kscale">${o.scale}</span>` : ''}
    <div class="lf-k" style="grid-template-columns:repeat(${cols},1fr)">${cells}</div>
    ${o.cap ? `<div class="label lf-kcap">${o.cap}</div>` : ''}</div>`;
};

const cols = (a, b, o = {}) => `<div class="lf-cols${o.cls ? ' ' + o.cls : ''}" style="${o.ratio ? `grid-template-columns:${o.ratio};` : ''}${o.style || ''}">
  <div class="lf-col">${a}</div><div class="lf-col">${b}</div></div>`;

