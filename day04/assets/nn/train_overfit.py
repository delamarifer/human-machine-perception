#!/usr/bin/env python3
"""Overfitting on the digit network of train_digits.py: the same data, split, network and training rule,
trained on a small subset of the training digits, with the loss and accuracy on the training digits and on
the 497 test digits recorded along the way. Writes overfit.js for day04/scenes/nn-overfit.html.

    python3 train_overfit.py       (needs numpy and scikit-learn)
"""
import json, os, sys
import numpy as np
from sklearn.datasets import load_digits

rng = np.random.default_rng(0)
X, y = load_digits(return_X_y=True)
X = X / 16.0
idx = rng.permutation(len(X)); X, y = X[idx], y[idx]
ntr = 1300
Xall, yall, Xte, yte = X[:ntr], y[:ntr], X[ntr:], y[ntr:]
SIZES = [64, 16, 16, 10]

def init(r):
    return [(r.normal(0, np.sqrt(2 / a), (a, b)), np.zeros(b)) for a, b in zip(SIZES[:-1], SIZES[1:])]
def forward(P, X):
    acts = [X]
    for i, (W, b) in enumerate(P):
        z = acts[-1] @ W + b
        acts.append(np.maximum(z, 0) if i < len(P) - 1 else z)
    z = acts[-1] - acts[-1].max(1, keepdims=True)
    p = np.exp(z); p /= p.sum(1, keepdims=True)
    return acts, p
def stats(P, X, y):
    _, p = forward(P, X)
    return float(-np.log(p[np.arange(len(y)), y] + 1e-12).mean()), float((p.argmax(1) == y).mean())
def grads(P, X, y):
    acts, p = forward(P, X)
    d = p.copy(); d[np.arange(len(y)), y] -= 1; d /= len(y)
    G = []
    for i in range(len(P) - 1, -1, -1):
        W, b = P[i]
        G.append((acts[i].T @ d, d.sum(0)))
        if i: d = (d @ W.T) * (acts[i] > 0)
    return G[::-1]

def train(n, steps, every, lr=0.5, seed=0):
    Xtr, ytr = Xall[:n], yall[:n]
    r = np.random.default_rng(seed); r.permutation(len(X))       # same starting weights as train_digits.py
    P = init(r); rec = []
    for t in range(steps + 1):
        if t % every == 0: rec.append([t, *stats(P, Xtr, ytr), *stats(P, Xte, yte)])
        if t == steps: break
        G = grads(P, Xtr, ytr)
        P = [(W - lr * gW, b - lr * gb) for (W, b), (gW, gb) in zip(P, G)]
    return rec

if __name__ == '__main__':
    for n in map(int, sys.argv[1:]):
        r = train(n, 3000, 100)
        best = min(r, key=lambda q: q[3])
        print(n, 'end train loss %.3f acc %.2f | test loss %.3f acc %.3f | best test loss %.3f at step %d' % (r[-1][1], r[-1][2], r[-1][3], r[-1][4], best[3], best[0]))

    SMALL, STEPS, EVERY = 100, 1500, 10
    out = {'source': 'scikit-learn load_digits (UCI Optical Recognition of Handwritten Digits, CC BY 4.0); trained by train_overfit.py',
           'sizes': SIZES, 'ntest': int(len(yte)), 'steps': STEPS, 'every': EVERY,
           'columns': ['step', 'train loss', 'train accuracy', 'test loss', 'test accuracy'],
           'runs': {str(n): np.round(train(n, STEPS, EVERY), 4).tolist() for n in (SMALL, ntr)}}
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'overfit.js'), 'w') as f:
        f.write('/* Generated by train_overfit.py. Do not edit by hand. */\nconst OVERFIT = ' + json.dumps(out, separators=(',', ':')) + ';\n')
    for n, r in out['runs'].items():
        b = min(r, key=lambda q: q[3])
        print(n, 'final', r[-1], 'best test loss', b)
