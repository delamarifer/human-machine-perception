#!/usr/bin/env python3
"""Trains the small digit network shown in day04/scenes/nn-digits.html and nn-descent.html.

    python3 train_digits.py        (needs numpy and scikit-learn; writes digits.js next to this file)

Data: the 8x8 handwritten digits bundled with scikit-learn (UCI "Optical Recognition of Handwritten
Digits", Alpaydin & Kaynak, 1998, CC BY 4.0). Network: 64 -> 16 -> 16 -> 10, ReLU, softmax,
cross-entropy, full-batch gradient descent, fixed seed. Everything the scenes show comes from here:
the weights, the test digits, the accuracy, the loss surface (a 2D slice of the real loss through the
starting and final weights) and the training path projected onto that slice.
"""
import json, os
import numpy as np
from sklearn.datasets import load_digits

rng = np.random.default_rng(0)
X, y = load_digits(return_X_y=True)
X = X / 16.0
idx = rng.permutation(len(X)); X, y = X[idx], y[idx]
ntr = 1300
Xtr, ytr, Xte, yte = X[:ntr], y[:ntr], X[ntr:], y[ntr:]
SIZES = [64, 16, 16, 10]

def init():
    return [(rng.normal(0, np.sqrt(2 / a), (a, b)), np.zeros(b)) for a, b in zip(SIZES[:-1], SIZES[1:])]

def flat(P): return np.concatenate([np.concatenate([W.ravel(), b]) for W, b in P])
def unflat(v):
    P, k = [], 0
    for a, b in zip(SIZES[:-1], SIZES[1:]):
        W = v[k:k + a * b].reshape(a, b); k += a * b
        c = v[k:k + b]; k += b
        P.append((W, c))
    return P

def forward(P, X):
    acts = [X]
    for i, (W, b) in enumerate(P):
        z = acts[-1] @ W + b
        acts.append(np.maximum(z, 0) if i < len(P) - 1 else z)
    z = acts[-1] - acts[-1].max(1, keepdims=True)
    p = np.exp(z); p /= p.sum(1, keepdims=True)
    return acts, p

def loss(P, X, y):
    _, p = forward(P, X)
    return float(-np.log(p[np.arange(len(y)), y] + 1e-12).mean())

def grads(P, X, y):
    acts, p = forward(P, X)
    d = p.copy(); d[np.arange(len(y)), y] -= 1; d /= len(y)
    G = []
    for i in range(len(P) - 1, -1, -1):
        W, b = P[i]
        G.append((acts[i].T @ d, d.sum(0)))
        if i: d = (d @ W.T) * (acts[i] > 0)
    return G[::-1]

P = init(); theta0 = flat(P)
LR, STEPS, EVERY = 0.5, 1500, 25
path = [theta0.copy()]; losses = [loss(P, Xtr, ytr)]
for t in range(1, STEPS + 1):
    G = grads(P, Xtr, ytr)
    P = [(W - LR * gW, b - LR * gb) for (W, b), (gW, gb) in zip(P, G)]
    if t % EVERY == 0:
        path.append(flat(P)); losses.append(loss(P, Xtr, ytr))
theta1 = flat(P)
_, pte = forward(P, Xte)
acc = float((pte.argmax(1) == yte).mean())
print(f'train loss {losses[0]:.3f} -> {losses[-1]:.3f}, test accuracy {acc:.3f} on {len(yte)} digits')

# 2D slice: d1 = theta1 - theta0, d2 = a random direction orthogonal to d1, same length
d1 = theta1 - theta0
r = rng.normal(size=d1.shape); r -= r @ d1 / (d1 @ d1) * d1; d2 = r / np.linalg.norm(r) * np.linalg.norm(d1)
A = np.linspace(-0.3, 1.3, 49); B = np.linspace(-0.8, 0.8, 41)
grid = [[loss(unflat(theta0 + a * d1 + b * d2), Xtr, ytr) for a in A] for b in B]
proj = [[float((th - theta0) @ d1 / (d1 @ d1)), float((th - theta0) @ d2 / (d2 @ d2))] for th in path]

# a few test digits, one per class
show = [int(np.where(yte == c)[0][0]) for c in range(10)]
out = {
  'source': 'scikit-learn load_digits (UCI Optical Recognition of Handwritten Digits, CC BY 4.0); trained by train_digits.py',
  'sizes': SIZES, 'lr': LR, 'steps': STEPS, 'ntrain': ntr, 'ntest': int(len(yte)), 'testAccuracy': round(acc, 4),
  'weights': [[np.round(W, 4).tolist(), np.round(b, 4).tolist()] for W, b in P],
  'digits': [{'label': int(yte[i]), 'pixels': np.round(Xte[i], 4).tolist(), 'predicted': int(pte[i].argmax())} for i in show],
  'surface': {'alpha': np.round(A, 4).tolist(), 'beta': np.round(B, 4).tolist(), 'loss': np.round(grid, 4).tolist()},
  'path': {'every': EVERY, 'ab': np.round(proj, 4).tolist(), 'loss': np.round(losses, 4).tolist()},
}
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, 'digits.js'), 'w') as f:
    f.write('/* Generated by train_digits.py. Do not edit by hand. */\nconst DIGITS = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print('wrote digits.js')
